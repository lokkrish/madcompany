import fs from 'node:fs';
import path from 'node:path';
import { ensureDir } from '../paths.js';

/**
 * Readable markdown copies of HQ's state under .madcompany/log/, so the
 * history can be read (and diffed, and versioned) without HQ running.
 * Every ticket, decision and question gets an anchor, so IDs stay clickable.
 */
const esc = (s) => String(s ?? '').replace(/\|/g, '\\|').replace(/\n+/g, ' ');
const day = (ts) => (ts ? ts.replace('T', ' ').slice(0, 16) : '');

export function channelFile(channel) {
  return `${channel.replace(/:/g, '-')}.md`;
}

export function renderBoard(state) {
  const tickets = Object.values(state.tickets).sort((a, b) => Number(a.id.split('-')[1]) - Number(b.id.split('-')[1]));
  const out = ['# Board', '', `Generated by madcompany HQ. ${tickets.length} tickets.`, '', '| Ticket | Title | Status | Assignee | Release / epic | Depends on |', '|---|---|---|---|---|---|'];
  for (const t of tickets) {
    out.push(`| [${t.id}](#${t.id.toLowerCase()}) | ${esc(t.title)} | ${t.status} | ${t.assignee ?? ''} | ${t.release ?? t.epic ?? ''} | ${t.deps.map((d) => `[${d}](#${d.toLowerCase()})`).join(', ')} |`);
  }
  for (const t of tickets) {
    out.push('', `## <a id="${t.id.toLowerCase()}"></a>${t.id}: ${t.title}`, '');
    out.push(`- **Status:** ${t.status}${t.blockedBy.length ? ` (blocked by ${t.blockedBy.join(', ')})` : ''}`);
    out.push(`- **Assignee:** ${t.assignee ?? 'nobody'} · **Kind:** ${t.kind}${t.ui ? ' · UI' : ''} · **Attempts:** ${t.attempts}`);
    if (t.refs.length) out.push(`- **Refs:** ${t.refs.join(', ')}`);
    if (t.body) out.push('', t.body.trim());
    if (t.checkpoint) out.push('', `**Checkpoint** (${t.checkpoint.by}, ${day(t.checkpoint.ts)}): done — ${t.checkpoint.done}; next — ${t.checkpoint.next}`);
    if (t.activity.length) {
      out.push('', '| When | Who | What |', '|---|---|---|');
      for (const a of t.activity) out.push(`| ${day(a.ts)} | ${a.by} | ${esc(a.text)} |`);
    }
  }
  return out.join('\n') + '\n';
}

export function renderDecisions(state) {
  const out = ['# Decisions', '', 'Decisions the team made without you. Newest last.'];
  for (const d of state.decisions) {
    out.push('', `## <a id="${d.id.toLowerCase()}"></a>${d.id}: ${d.title}`, '', `- **By:** ${d.by}, ${day(d.ts)}${d.ticket ? ` · **Ticket:** ${d.ticket}` : ''}`, `- **Decision:** ${d.decision}`, `- **Why:** ${d.why}`);
    if (d.alternatives) out.push(`- **Alternatives:** ${d.alternatives}`);
    if (d.links?.length) out.push(`- **Links:** ${d.links.join(', ')}`);
  }
  return out.join('\n') + '\n';
}

export function renderQuestions(state) {
  const out = ['# Questions', '', 'Every question asked on the team, who it went to and the answer.'];
  for (const q of Object.values(state.questions)) {
    out.push('', `## <a id="${q.id.toLowerCase()}"></a>${q.id}: ${esc(q.question)}`, '', `- **From:** ${q.from} → **to:** ${q.to} (route: ${q.trail.join(' → ')})`, `- **Status:** ${q.status}${q.ticket ? ` · **Ticket:** ${q.ticket}` : ''}`);
    if (q.options.length) out.push(`- **Options:** ${q.options.join(' / ')}${q.recommended ? ` (recommended: ${q.recommended})` : ''}`);
    if (q.answer) out.push(`- **Answer** (${q.answeredBy}, ${day(q.answeredAt)}): ${q.answer}`);
  }
  return out.join('\n') + '\n';
}

const KIND = { account: 'Accounts & sign-ups', secret: 'Keys & secrets', setup: 'Service setup', money: 'Payments & purchases', ship: 'Push, deploy & publish', access: 'Access, data & legal', other: 'Other' };

/** Everything only you can do, open items first. Readable without HQ. */
export function renderHumanHelp(state) {
  const items = Object.values(state.help ?? {});
  const open = items.filter((h) => h.status === 'open');
  const out = ['# Human help', '', 'Things only you can do: accounts, keys, service setup, payments, pushes and deploys, access. Agents file them; tickets waiting on one resume when you mark it done in HQ → Human help.', ''];
  out.push(`${open.length} open, ${items.length - open.length} done or cancelled.`);
  const one = (h) => {
    out.push('', `## <a id="${h.id.toLowerCase()}"></a>${h.id}: ${h.title}`, '');
    out.push(`- **Status:** ${h.status}${h.doneBy ? ` (${h.doneBy}, ${day(h.doneAt)})` : ''} · **Kind:** ${KIND[h.kind] ?? h.kind}${h.service ? ` · **Service:** ${h.service}` : ''}${h.neededBy ? ` · **Needed by:** ${h.neededBy}` : ''}`);
    out.push(`- **Asked by:** ${h.by}, ${day(h.ts)}${h.tickets.length ? ` · **Tickets:** ${h.tickets.map((t) => `[${t}](log/board.md#${t.toLowerCase()})`).join(', ')}` : ''}`);
    if (h.why) out.push(`- **Why:** ${h.why}`);
    if (h.env.length) out.push(`- **Add to .env:** ${h.env.map((k) => `\`${k}\``).join(', ')}`);
    if (h.steps.length) out.push('', ...h.steps.map((x, i) => `${i + 1}. ${x}`));
    if (h.links.length) out.push('', `Links: ${h.links.join(', ')}`);
    if (h.note) out.push('', `Note: ${h.note}`);
  };
  open.forEach(one);
  items.filter((h) => h.status !== 'open').forEach(one);
  return out.join('\n') + '\n';
}

/** Requirements defined in HQ and amendments to any requirement, each with the change behind it. */
export function renderRequirements(st) {
  const reqs = Object.values(st.requirements ?? {});
  const amendments = st.amendments ?? [];
  const out = ['# Requirements from HQ', '', 'Requirements the team defined (from the brief, the MVP scope or a change request) and amendments to existing ones. The PRD is never edited. An amendment is proposed until the change behind it is done; then the latest one holds.'];
  // proposed until the change behind it is done; dropped if that change is withdrawn
  const state = (change) => {
    const c = change ? st.tickets[change] : null;
    return !c ? '' : c.withdrawn ? ' · **Withdrawn**' : c.status !== 'done' ? ` · **Proposed** until ${change} is done` : '';
  };
  for (const r of reqs) {
    out.push('', `## <a id="${r.id.toLowerCase()}"></a>${r.id}: ${r.title}`, '');
    out.push(`- **Kind:** ${r.kind} · **Added by:** ${r.by}, ${day(r.ts)}${r.change ? ` · **Change:** [${r.change}](board.md#${r.change.toLowerCase()})` : ''}${r.extends?.length ? ` · **Extends:** ${r.extends.join(', ')}` : ''}${r.source ? ` · **Source:** ${r.source}` : ''}${state(r.change)}`);
    out.push('', r.text);
  }
  if (amendments.length) {
    out.push('', '## Amendments', '');
    for (const a of amendments) out.push(`- **${a.id}**, ${day(a.ts)} by ${a.by}${a.change ? ` for [${a.change}](board.md#${a.change.toLowerCase()})` : ''}${state(a.change)}: ${esc(a.text)}`);
  }
  return out.join('\n') + '\n';
}

/** What team members noted about stories and requirements, by what it's about. */
export function renderNotes(state) {
  const out = ['# Notes', '', 'What team members know about a story, requirement or ticket. Agents add them with mc_note; mc_ref shows them under the ID.'];
  for (const n of state.notes ?? []) {
    out.push('', `## <a id="${n.id.toLowerCase()}"></a>${n.id}: ${n.about.join(', ')}`, '', `- **By:** ${n.by}, ${day(n.ts)} · **Scope:** ${n.scope}`, '', n.text);
  }
  return out.join('\n') + '\n';
}

export function renderChannel(channel, messages) {
  const out = [`# #${channel}`, ''];
  for (const m of messages) out.push(`**${m.by}** · ${day(m.ts)}  `, m.text, '');
  return out.join('\n');
}

export function createViewWriter(core, { delayMs = 400, onWritten } = {}) {
  const { store, paths } = core;
  let timer = null;
  const dirtyChannels = new Set();

  function writeAll() {
    timer = null;
    ensureDir(paths.chat);
    const s = store.state;
    fs.writeFileSync(path.join(paths.log, 'board.md'), renderBoard(s));
    fs.writeFileSync(path.join(paths.log, 'decisions.md'), renderDecisions(s));
    fs.writeFileSync(path.join(paths.log, 'questions.md'), renderQuestions(s));
    if (Object.keys(s.help ?? {}).length) fs.writeFileSync(path.join(paths.dir, 'human-help.md'), renderHumanHelp(s));
    if (Object.keys(s.requirements ?? {}).length || s.amendments?.length) fs.writeFileSync(path.join(paths.log, 'requirements.md'), renderRequirements(s));
    if (s.notes?.length) fs.writeFileSync(path.join(paths.log, 'notes.md'), renderNotes(s));
    for (const c of dirtyChannels) {
      fs.writeFileSync(path.join(paths.chat, channelFile(c)), renderChannel(c, s.messages.filter((m) => m.channel === c)));
    }
    dirtyChannels.clear();
    onWritten?.();
  }

  store.on('event', (ev) => {
    if (ev.type === 'msg.post') dirtyChannels.add(ev.data.channel);
    if (!timer) timer = setTimeout(writeAll, delayMs);
  });

  return {
    flush() {
      if (timer) clearTimeout(timer);
      for (const m of store.state.messages) dirtyChannels.add(m.channel);
      writeAll();
    },
  };
}
